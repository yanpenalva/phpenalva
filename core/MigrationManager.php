<?php

declare(strict_types=1);

namespace Core;

use PDO;
use PDOStatement;
use RuntimeException;
use Throwable;
use function dirname;
use function extension_loaded;
use function in_array;
use function is_string;
use function sprintf;

final class MigrationManager
{
    private const SUPPORTED_DRIVERS = ['sqlite', 'mysql', 'pgsql', 'sqlsrv'];

    private const MIGRATIONS = [
        \CreateUsersTable::class => [],
        \CreatePostsTable::class => [\CreateUsersTable::class],
    ];

    private const ROLLBACK_ORDER = [
        \CreatePostsTable::class,
        \CreateUsersTable::class,
    ];

    private PDO $pdo;

    public function __construct(PDO $pdo)
    {
        $this->pdo = $pdo;
        $migrationDirectory = sprintf('%s/database/migrations', dirname(__DIR__));
        require_once sprintf('%s/CreateUsersTable.php', $migrationDirectory);
        require_once sprintf('%s/CreatePostsTable.php', $migrationDirectory);
        $this->createMigrationTable();
    }

    /**
     * @return array<int, string>
     */
    public function migrate(): array
    {
        $appliedMigrations = $this->getAppliedMigrations();
        $this->assertHistoryConsistent($appliedMigrations);
        $migrated = [];

        foreach (self::MIGRATIONS as $migrationName => $dependencies) {
            $alreadyApplied = in_array($migrationName, $appliedMigrations, true);

            if ($alreadyApplied) {
                continue;
            }

            foreach ($dependencies as $dependency) {
                $dependencyIsApplied = in_array($dependency, $appliedMigrations, true);

                if (!$dependencyIsApplied) {
                    throw new RuntimeException(sprintf('Migration dependency %s is not applied.', $dependency));
                }
            }

            $this->runUp($migrationName);
            $appliedMigrations[] = $migrationName;
            $migrated[] = $migrationName;
        }

        return $migrated;
    }

    /**
     * @return array<int, string>
     */
    public function rollback(bool $force = false): array
    {
        if (!$force) {
            throw new RuntimeException('Rollback drops schema; pass --force after arranging a backup.');
        }

        $appliedMigrations = $this->getAppliedMigrations();
        $this->assertHistoryConsistent($appliedMigrations);
        $rolledBack = [];

        foreach (self::ROLLBACK_ORDER as $migrationName) {
            $isApplied = in_array($migrationName, $appliedMigrations, true);

            if (!$isApplied) {
                continue;
            }

            $this->runDown($migrationName);
            $rolledBack[] = $migrationName;
        }

        return $rolledBack;
    }

    /**
     * @return array<int, string>
     */
    public function rollbackLast(bool $force = false): array
    {
        if (!$force) {
            throw new RuntimeException('Rollback drops schema; pass --force after arranging a backup.');
        }

        $appliedMigrations = $this->getAppliedMigrations();
        $this->assertHistoryConsistent($appliedMigrations);

        foreach (self::ROLLBACK_ORDER as $migrationName) {
            $isApplied = in_array($migrationName, $appliedMigrations, true);

            if (!$isApplied) {
                continue;
            }

            $this->runDown($migrationName);

            return [$migrationName];
        }

        return [];
    }

    private function createMigrationTable(): void
    {
        $sql = match ($this->driverName()) {
            'sqlite' => 'CREATE TABLE IF NOT EXISTS migrations (id INTEGER PRIMARY KEY AUTOINCREMENT, migration VARCHAR(255) NOT NULL UNIQUE, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)',
            'mysql' => 'CREATE TABLE IF NOT EXISTS migrations (id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, migration VARCHAR(255) NOT NULL UNIQUE, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP) ENGINE=InnoDB',
            'pgsql' => 'CREATE TABLE IF NOT EXISTS migrations (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, migration VARCHAR(255) NOT NULL UNIQUE, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)',
            'sqlsrv' => "IF OBJECT_ID(N'migrations', N'U') IS NULL CREATE TABLE migrations (id BIGINT IDENTITY(1,1) PRIMARY KEY, migration NVARCHAR(255) NOT NULL UNIQUE, created_at DATETIME2 NOT NULL DEFAULT GETDATE())",
            default => throw new RuntimeException('Unsupported PDO driver for migration history.'),
        };

        $result = $this->pdo->exec($sql);

        if ($result === false) {
            throw new RuntimeException('Unable to create the migration history table.');
        }
    }

    private function driverName(): string
    {
        $driverName = (string) $this->pdo->getAttribute(PDO::ATTR_DRIVER_NAME);
        $driverIsSupported = in_array($driverName, self::SUPPORTED_DRIVERS, true);

        if (!$driverIsSupported) {
            throw new RuntimeException('Unsupported PDO driver for migrations.');
        }

        $requiresSqlServerExtension = $driverName === 'sqlsrv' && !extension_loaded('pdo_sqlsrv');

        if ($requiresSqlServerExtension) {
            throw new RuntimeException('SQL Server migrations require the PDO_SQLSRV extension.');
        }

        return $driverName;
    }

    /**
     * @return array<int, string>
     */
    private function getAppliedMigrations(): array
    {
        $statement = $this->pdo->query('SELECT migration FROM migrations ORDER BY id ASC');

        if (!$statement instanceof PDOStatement) {
            throw new RuntimeException('Unable to read migration history.');
        }

        $migrations = [];

        foreach ($statement->fetchAll(PDO::FETCH_COLUMN) as $migrationName) {
            $migrationNameIsString = is_string($migrationName);

            if (!$migrationNameIsString) {
                throw new RuntimeException('Migration history contains an invalid record.');
            }

            $migrations[] = (string) $migrationName;
        }

        return $migrations;
    }

    /**
     * @param array<int, string> $appliedMigrations
     */
    private function assertHistoryConsistent(array $appliedMigrations): void
    {
        foreach ($appliedMigrations as $migrationName) {
            $dependencies = self::MIGRATIONS[$migrationName] ?? null;

            if ($dependencies === null) {
                throw new RuntimeException(sprintf('Unknown migration history record: %s.', $migrationName));
            }

            foreach ($dependencies as $dependency) {
                $dependencyIsApplied = in_array($dependency, $appliedMigrations, true);

                if (!$dependencyIsApplied) {
                    throw new RuntimeException(sprintf('Migration %s is recorded without dependency %s.', $migrationName, $dependency));
                }
            }
        }
    }

    private function runUp(string $migrationName): void
    {
        $migration = $this->newMigration($migrationName);
        $transactional = $this->driverName() !== 'mysql';
        $transactionStarted = true;

        if ($transactional) {
            $transactionStarted = $this->pdo->beginTransaction();
        }

        if (!$transactionStarted) {
            throw new RuntimeException('Unable to begin the migration transaction.');
        }

        try {
            $migration->up();
            $this->recordApplied($migrationName);

            if ($transactional) {
                $committed = $this->pdo->commit();
                if (!$committed) {
                    throw new RuntimeException('Unable to commit the migration transaction.');
                }
            }
        } catch (Throwable $exception) {
            $this->rollbackTransaction($transactional);
            throw $exception;
        }
    }

    private function runDown(string $migrationName): void
    {
        $migration = $this->newMigration($migrationName);
        $transactional = $this->driverName() !== 'mysql';
        $transactionStarted = true;

        if ($transactional) {
            $transactionStarted = $this->pdo->beginTransaction();
        }

        if (!$transactionStarted) {
            throw new RuntimeException('Unable to begin the rollback transaction.');
        }

        try {
            $migration->down(true);
            $this->removeMigration($migrationName);

            if ($transactional) {
                $committed = $this->pdo->commit();
                if (!$committed) {
                    throw new RuntimeException('Unable to commit the rollback transaction.');
                }
            }
        } catch (Throwable $exception) {
            $this->rollbackTransaction($transactional);
            throw $exception;
        }
    }

    private function newMigration(string $migrationName): BaseMigration
    {
        return match ($migrationName) {
            \CreateUsersTable::class => new \CreateUsersTable($this->pdo),
            \CreatePostsTable::class => new \CreatePostsTable($this->pdo),
            default => throw new RuntimeException('Unknown migration requested.'),
        };
    }

    private function recordApplied(string $migrationName): void
    {
        $statement = $this->pdo->prepare('INSERT INTO migrations (migration) VALUES (:migration)');

        if (!$statement instanceof PDOStatement) {
            throw new RuntimeException('Unable to prepare the migration history insert.');
        }

        $inserted = $statement->execute(['migration' => $migrationName]);

        if (!$inserted) {
            throw new RuntimeException('Unable to record the applied migration.');
        }
    }

    private function removeMigration(string $migrationName): void
    {
        $statement = $this->pdo->prepare('DELETE FROM migrations WHERE migration = :migration');

        if (!$statement instanceof PDOStatement) {
            throw new RuntimeException('Unable to prepare the migration history delete.');
        }

        $removed = $statement->execute(['migration' => $migrationName]);

        if (!$removed) {
            throw new RuntimeException('Unable to remove the rolled-back migration record.');
        }
    }

    private function rollbackTransaction(bool $transactional): void
    {
        if (!$transactional) {
            return;
        }

        $transactionActive = $this->pdo->inTransaction();

        if ($transactionActive) {
            $this->pdo->rollBack();
        }
    }
}
